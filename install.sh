# ── OS / package manager ───────────────────────────────────────────────
OS_ID="" OS_NAME="" PKG_INSTALL="" PKG_UPDATE=""

detect_os() {
    [[ -f /etc/os-release ]] || die "Unsupported OS — no /etc/os-release found."
    # /etc/os-release defines its own VERSION — keep the app version.
    local _app_version="$VERSION"
    # shellcheck disable=SC1091
    . /etc/os-release
    VERSION="$_app_version"
    OS_ID="${ID:-}"; OS_NAME="${PRETTY_NAME:-$OS_ID}"
    case "$OS_ID" in
        debian|ubuntu)      PKG_UPDATE="apt-get update -qq";  PKG_INSTALL="apt-get install -y -qq" ;;
        rhel|centos|rocky|almalinux|fedora)
            if command -v dnf >/dev/null 2>&1; then
                PKG_UPDATE="dnf -q makecache"; PKG_INSTALL="dnf install -y -q"
            else
                PKG_UPDATE="yum -q makecache"; PKG_INSTALL="yum install -y -q"
            fi ;;
        arch)               PKG_UPDATE="pacman -Sy --noconfirm"; PKG_INSTALL="pacman -S --noconfirm" ;;
        alpine)             PKG_UPDATE="apk update -q";          PKG_INSTALL="apk add -q" ;;
        *) die "Unsupported distribution: ${OS_ID:-unknown}" ;;
    esac
}

pkg_install() {
    info "Installing: $*"
    $PKG_UPDATE >/dev/null 2>&1 || true
    $PKG_INSTALL "$@" >/dev/null 2>&1 || die "Failed to install: $*"
}

# ── Help / args ────────────────────────────────────────────────────────
# One line per flag that left the three-flag surface. It goes to stderr and
# it is not routed through line()/warn(): those are silenced by --quiet and
# by a non-TTY, and a deprecation the operator never sees is not a
# deprecation. The flags still work — removal is the next release.
deprecated() {  # deprecated <flag> <what to do instead>
    printf '  %s⚠%s %s is deprecated; %s\n' "$YL" "$NC" "$1" "$2" >&2
}

# The installer's own identity, for support: "which installer did you
# actually run?". A curl-piped run is always the newest file, but the raw
# CDN caches for minutes, so a stale copy is normal rather than a mystery.
# printf, not field(): field() is silenced by --quiet, and this command
# exists precisely to be read back by somebody else. The commit is printed
# only when something stamped it — this installer has no code path that
# knows its own SHA, and inventing one would be worse than saying so.
print_script_version() {
    printf '  %-18s %s\n' "Installer" "install.sh v${VERSION}" >&2
    printf '  %-18s %s\n' "Commit" \
        "${OVN_SCRIPT_COMMIT:-not recorded (this installer carries no commit stamp)}" >&2
    exit "$EX_OK"
}

