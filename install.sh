#
# The ref to fetch is the one subtlety. "This installer's own VERSION" is right
# in principle — the libs are installer infrastructure, so `-v 1.0.2` must pin
# the app tarball and nothing else — but it is only correct while that tag is at
# least as new as this file, and it is not right now: tag v1.0.0's lib predates
# helpers this file needs. A curl-piped installer comes from a branch and names
# a tag it may not match, so the tag is tried first, main is the fallback, and
# the result is *checked* rather than trusted.
LIB_FILES=(common.sh)   # one entry per file in scripts/lib
LIBS_NEEDED=(die line info warn field sep ask confirm check_root compose_file has_systemd is_docker_node)
LIB_REFS=("v${VERSION}" main)

_libs_are_usable() {  # _libs_are_usable <dir> → 0 when it defines what we call
    # Sourced in a subshell on purpose: a candidate that turns out to be unusable
    # must not leave half its definitions behind for the next candidate to layer on.
    (
        for _l in "${LIB_FILES[@]}"; do
            # shellcheck disable=SC1090
            . "$1/$_l" || exit 1
        done
        for _f in "${LIBS_NEEDED[@]}"; do
            declare -F "$_f" >/dev/null || exit 1
        done
    )
}

# Guarded on purpose: `cat install.sh | bash -s --` (the documented pipe form)
# leaves BASH_SOURCE empty, and `set -u` turns that into "unbound variable"
# before a single line of setup runs. No source path means no local lib to
# look for, so skip straight to the fetch.
LIB_DIR=""
if [[ -n "${BASH_SOURCE[0]:-}" ]]; then
    LIB_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" 2>/dev/null && pwd || true)/scripts/lib"
    for _lib in "${LIB_FILES[@]}"; do
        [[ -f "$LIB_DIR/$_lib" ]] || LIB_DIR=""
    done
fi
if [[ -z "$LIB_DIR" ]]; then
    LIB_DIR=""
    for _ref in "${LIB_REFS[@]}"; do
        _url="https://raw.githubusercontent.com/${REPO}/${_ref}/scripts/lib"
        _try="$(mktemp -d /tmp/ovn-lib.XXXXXX)"
        _ok=1
        for _lib in "${LIB_FILES[@]}"; do
            curl -fsSL -o "$_try/$_lib" "$_url/$_lib" 2>/dev/null || { _ok=0; break; }
        done
        if [[ "$_ok" -eq 1 ]] && _libs_are_usable "$_try"; then
            LIB_DIR="$_try"
            break
        fi
        rm -rf "$_try"
    done
    if [[ -z "$LIB_DIR" ]]; then
        echo -e "\n  ${RD}Error:${NC} no usable scripts/lib for v${VERSION} or main — the installer cannot run without it. Re-bootstrap with the latest installer: bash <(curl -sSL https://raw.githubusercontent.com/${REPO}/main/install.sh)\n" >&2
        exit "$EX_ERROR"
    fi
fi
# Sourced only once a candidate is in place and known usable, so a partial or
# stale download can never leave a half-defined environment.
for _lib in "${LIB_FILES[@]}"; do
    # shellcheck disable=SC1090
    . "$LIB_DIR/$_lib"
done
[[ "$LIB_DIR" == /tmp/ovn-lib.* ]] && rm -rf "$LIB_DIR"
unset _lib _try _ref _url _ok _l _f

trap 'echo -e "\n  ${RD}Interrupted.${NC}" >&2; exit 130' INT TERM
