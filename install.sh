line()  { [[ "$QUIET" -eq 1 ]] || echo -e "  $1" >&2; }
step()  { line "${GR}  ✓${NC} $1"; }
info()  { line "${CY}  →${NC} $1"; }
warn()  { line "${YL}  ⚠${NC} $1"; }
