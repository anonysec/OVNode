# ── Output ─────────────────────────────────────────────────────────────
# Contract: ALL human-readable output goes to stderr. stdout carries
# exactly one JSON object in --json mode and nothing otherwise — so
# `RESULT=$(installer ... --json)` is always parseable.
NC=$'\033[0m'; B=$'\033[1m'
WH=$'\033[97m'; GR=$'\033[32m'; RD=$'\033[31m'
YL=$'\033[33m'; CY=$'\033[36m'; GY=$'\033[90m'
[[ -t 2 ]] || { NC=''; B=''; WH=''; GR=''; RD=''; YL=''; CY=''; GY=''; }

line()  { [[ "$QUIET" -eq 1 ]] || echo -e "  $1" >&2; }
step()  { line "${GR}  ✓${NC} $1"; }
info()  { line "${CY}  →${NC} $1"; }
warn()  { line "${YL}  ⚠${NC} $1"; }
field() { [[ "$QUIET" -eq 1 ]] || printf "  ${GY}%-18s${NC} %s\n" "$1" "$2" >&2; }
sep()   { line "${GY}$(printf '%.0s─' {1..56})${NC}"; }

json_escape() {  # minimal escaper for values we emit
    local s="${1//\\/\\\\}"; s="${s//\"/\\\"}"
    s="${s//$'\n'/ }"; s="${s//$'\t'/ }"
    printf '%s' "$s"
}

# die <message> [exit-code]  — single error path, JSON-aware.
die() {
    local msg="$1" code="${2:-$EX_ERROR}"
    echo -e "\n  ${RD}Error:${NC} $msg\n" >&2
    if [[ "$JSON" -eq 1 ]]; then
        printf '{"ok":false,"action":"%s","error":"%s","exit_code":%d}\n' \
            "$(json_escape "$ACTION")" "$(json_escape "$msg")" "$code"
    fi
    exit "$code"
}

trap 'echo -e "\n  ${RD}Interrupted.${NC}" >&2; exit 130' INT TERM
trap 'warn "Command failed near line $LINENO (running: ${BASH_COMMAND:0:80})"' ERR

is_tty() { [[ -t 0 && -t 2 ]]; }
# Spinners/prompts only for interactive humans; plain logs otherwise.
fancy()  { is_tty && [[ "$QUIET" -eq 0 && "$JSON" -eq 0 ]]; }

spinner() {
    local msg="$1" pid=$2 chars='⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏' i=0 rc=0
    while kill -0 "$pid" 2>/dev/null; do
        printf "\r  ${CY}%s${NC} %-46s" "${chars:$((i%9)):1}" "$msg" >&2
        sleep 0.1; i=$(( i + 1 ))
    done
    wait "$pid" 2>/dev/null || rc=$?
    printf "\r\033[K" >&2
    [[ $rc -eq 0 ]] && step "$msg" || { line "${RD}  ✗${NC} $msg"; return $rc; }
}

# run <label> <cmd...> — required step: spinner on a TTY, plain log lines
# in automation. Fails the install with a clear message on error.
run() {
    local label="$1"; shift
    if fancy; then
        ( "$@" ) >/dev/null 2>&1 &
        spinner "$label" $! || die "Step failed: $label"
    else
        "$@" >/dev/null 2>&1 || die "Step failed: $label"
        step "$label"
    fi
}

# try_run <label> <cmd...> — best-effort step: warns instead of dying.
try_run() {
    local label="$1"; shift
    if fancy; then
        ( "$@" ) >/dev/null 2>&1 &
        spinner "$label" $! || { warn "$label — failed (continuing)"; return 1; }
    else
        if "$@" >/dev/null 2>&1; then step "$label"; else
            warn "$label — failed (continuing)"; return 1
        fi
    fi
}

ask() {
    local label="$1" default="$2" hidden="${3:-}" val=""
    if is_tty && [[ "$YES" -eq 0 ]]; then
        printf "  ${WH}%-24s${NC} ${GY}[%s]${NC} : " "$label" "$default" >&2
        if [[ "$hidden" == "h" ]]; then read -rs val; printf "\n" >&2; else read -r val; fi
    fi
    echo "${val:-$default}"
}

confirm() {
    [[ "$YES" -eq 1 ]] && return 0
    is_tty || return 0
    printf "  %s [${GR}Y${NC}/n] : " "$1" >&2
    read -r c
    [[ ! "$c" =~ ^[Nn]$ ]]
}

# ── OS / package manager ───────────────────────────────────────────────
OS_ID="" OS_NAME="" PKG_INSTALL="" PKG_UPDATE=""

detect_os() {
    [[ -f /etc/os-release ]] || die "Unsupported OS — no /etc/os-release found."
    # shellcheck disable=SC1091
    . /etc/os-release
    OS_ID="${ID:-}"; OS_NAME="${PRETTY_NAME:-$OS_ID}"
    case "$OS_ID" in
        debian|ubuntu)      PKG_UPDATE="apt-get update -qq";  PKG_INSTALL="apt-get install -y -qq" ;;
        rhel|centos|rocky|almalinux|fedora)
            if command -v dnf >/dev/null 2>&1; then
                PKG_UPDATE="dnf -q makecache"; PKG_INSTALL="dnf install -y -q"
            else
                PKG_UPDATE="yum -q makecache"; PKG_INSTALL="yum install -y -q"
            fi ;;
        arch)               PKG_UPDATE="pacman -Sy --noconfirm"; PKG_INSTALL="pacman -S --noconfirm" ;;
        alpine)             PKG_UPDATE="apk update -q";          PKG_INSTALL="apk add -q" ;;
        *) die "Unsupported distribution: ${OS_ID:-unknown}" ;;
    esac
}

pkg_install() {
    info "Installing: $*"
    $PKG_UPDATE >/dev/null 2>&1 || true
    $PKG_INSTALL "$@" >/dev/null 2>&1 || die "Failed to install: $*"
}

