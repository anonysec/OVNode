# ── Interactive setup (humans on a TTY) ────────────────────────────────
interactive_setup() {
    local api_default
    api_default="$(openssl rand -hex 32)"
    line "${B}Step 1/4 — Node identity${NC}"
    NODE_NAME="$(ask "Node name" "${NODE_NAME:-ovnode}")"
    PORT="$(ask "Service port" "${PORT:-$(find_free_port "$DEFAULT_PORT")}")"
    VPN_PORTS="$(ask "OpenVPN port(s), comma sep." "${VPN_PORTS:-$DEFAULT_VPN}")"
    API_KEY="$(ask "API key (blank=generate)" "${API_KEY:-$api_default}")"

    # Transport: UDP is faster (no TCP-over-TCP meltdown); TCP only where
    # DPI/firewalls block UDP. Interactive default is UDP; unattended
    # installs stay on TCP (previous behavior, zero surprise).
    if [[ -z "$VPN_PROTO" ]]; then
        if is_tty && [[ "$YES" -eq 0 ]]; then
            line ""
            line "${B}Step 2/4 — VPN transport${NC}"
            line "  ${WH}1${NC})  UDP — faster, recommended"
            line "  ${WH}2${NC})  TCP — only where UDP is blocked"
            local proto_choice; proto_choice="$(ask "Transport" "1")"
            [[ "$proto_choice" == "2" ]] && VPN_PROTO="tcp" || VPN_PROTO="udp"
        else
            VPN_PROTO="tcp"
        fi
    fi

    if [[ "$DOCKER" -eq 0 ]]; then
        line ""
        line "${B}Step 3/4 — Deployment${NC}"
        line "  ${WH}1${NC})  Host — systemd service (recommended)"
        line "  ${WH}2${NC})  Docker — agent + OpenVPN in one container"
        local dep; dep="$(ask "Mode" "1")"
        [[ "$dep" == "2" ]] && DOCKER=1
    fi

    line ""
    line "${B}Step 4/4 — Certificate (always encrypted)${NC}"
    line "  ${WH}1${NC})  Self-signed (default)     encrypted; turn TLS *on* in the panel"
    line "  ${WH}2${NC})  Let's Encrypt (domain)    needs a domain pointed here + free port 80"
    line "  ${WH}3${NC})  Let's Encrypt (this IP)   short-lived cert, no domain needed"
    line "  ${WH}4${NC})  Custom cert path          bring your own key + cert files"
    local tls_choice
    tls_choice="$(ask "TLS mode" "1")"
    case "${tls_choice:-1}" in
        1) TLS_METHOD="selfsigned" ;;
        2) TLS_METHOD="letsencrypt"; TLS_DOMAIN="$(ask "Domain" "")"; [[ -n "$TLS_DOMAIN" ]] || die "Domain required for Let's Encrypt" ;;
        3) TLS_METHOD="letsencrypt-ip"; TLS_DOMAIN="$(primary_ip)" ;;
        4) TLS_METHOD="custom"; TLS_KEY="$(ask "Key file" "")"; TLS_CERT="$(ask "Cert file" "")" ;;
        *) TLS_METHOD="selfsigned" ;;
    esac
}

# Express install: safe defaults, no further questions. TLS is always on.
apply_express_defaults() {
    : "${PORT:=$(find_free_port "$DEFAULT_PORT")}"
    : "${VPN_PORTS:=$DEFAULT_VPN}"
    : "${NODE_NAME:=ovnode}"
    : "${VPN_PROTO:=udp}"
    TLS_METHOD="selfsigned"
    [[ -n "$API_KEY" ]] || generate_api_key
    EXPRESS=1
}

# Friendly front door: shown only for a bare interactive invocation.
# Host install is the default; Docker is the explicit second choice.
start_menu() {
    line "  ${B}OVNode Setup${NC}"
    sep
    line ""
    line "  ${GR}1.${NC} Install              ${GY}Recommended${NC}"
    line "  ${WH}2.${NC} Install with Docker"
    line ""
    line "  ${WH}0.${NC} Exit"
    line ""
    local choice
    choice="$(ask "Select" "1")"
    case "${choice:-1}" in
        1) apply_express_defaults ;;
        2) DOCKER=1; apply_express_defaults ;;
        0) line "Cancelled. No changes were made."; exit "$EX_OK" ;;
        *) warn "Choose 0, 1, or 2."; start_menu ;;
    esac
    line ""
}


# ── Terminal command (TUI) ─────────────────────────────────────────────
# install_cli() copies this installer to $BIN_DIR as "ovnode" (+ "ovn"), so a
# bare `ovnode` opens the menu. Every action is also a subcommand for scripts:
# status | start | stop | restart | restart-vpn | logs [N|-f] | backup |
# update | tls | uninstall | menu | help.

# systemd waits up to TimeoutStopSec for a stuck unit; bound the wait so an
# uninstall/update never looks frozen, then force the unit.
STOP_TIMEOUT="${OVN_STOP_TIMEOUT:-20}"





# Keep only the newest N tarballs this installer writes (/var/backups).

# Host-level daily backup: a systemd timer running `ovnode backup`.






installed_menu() {
    warn "OVNode is already installed"
    info "Manage the node with: ovn  (status, logs, backup, TLS)"
    while true; do
        local tag
        tag="$(tui_select "OVNode — installer" \
            update      "Update" \
            uninstall   "Uninstall" \
            quit        "Quit")"
        case "$tag" in
            update)      do_update || warn "Update failed" ;;
            uninstall)
                confirm_no "Also delete data and backups?" && PURGE=1
                do_uninstall
                return 0 ;;
            *)           return 0 ;;
        esac
    done
}

install_cli() {
    # The manager is the day-to-day command (ovnode/ovn). Refreshed on
    # every update, which auto-swaps boxes whose ovn is an old installer copy.
    local src="${APP_DIR}/manager.sh"
    [[ -f "$src" ]] || return 0
    mkdir -p "$BIN_DIR" 2>/dev/null || { warn "Could not create $BIN_DIR"; return 0; }
    if cp -f "$src" "$BIN_DIR/$CLI_NAME" 2>/dev/null && chmod 0755 "$BIN_DIR/$CLI_NAME"; then
        ln -sf "$CLI_NAME" "$BIN_DIR/$CLI_ALIAS" 2>/dev/null || true
        step "Command  ${BIN_DIR}/${CLI_NAME}  (alias: ${CLI_ALIAS})"
    else
        warn "Could not install the $CLI_NAME command into $BIN_DIR"
    fi
}

remove_cli() {
    rm -f "$BIN_DIR/$CLI_NAME" "$BIN_DIR/$CLI_ALIAS" 2>/dev/null || true
    # `ovn completion` writes this; leaving it behind completes a command
    # that no longer exists.
    rm -f "${OVN_COMPLETION_DIR:-/etc/bash_completion.d}/ovn" 2>/dev/null || true
}

# ── Preconditions ──────────────────────────────────────────────────────
check_deps() {
    local missing=() cmd
    for cmd in curl tar openssl git; do
        command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
    done
    # Native mode runs the agent + OpenVPN on the host; Docker bundles both
    # in the image, so the host needs neither python nor openvpn.
    if [[ "$DOCKER" -eq 0 ]]; then
        command -v python3 >/dev/null 2>&1 || missing+=("python3")
    fi
    [[ ${#missing[@]} -eq 0 ]] || pkg_install "${missing[@]}"
    if [[ "$DOCKER" -eq 0 ]] && ! command -v openvpn >/dev/null 2>&1; then
        info "Installing OpenVPN + easy-rsa (for client PKI)..."
        pkg_install openvpn easy-rsa
    fi
    step "System dependencies present"
}

# ── Main ───────────────────────────────────────────────────────────────
main() {
    parse_args "$@"
    [[ -n "${OVN_SRC:-}" && "${OVN_SRC}" != "release" ]] && die "Source installs were removed — the installer consumes verified releases only (developers: clone the repo)" "$EX_USAGE"
    [[ -n "${OVN_BRANCH:-}" ]] && die "OVN_BRANCH was removed with source installs — developers: git checkout the branch in a clone" "$EX_USAGE"
    case "$SRC" in
        release) ;;
        *) die "Invalid source '$SRC' (releases only)" "$EX_USAGE" ;;
    esac
    if [[ -n "$PIN" ]]; then
        valid_release_version "$PIN" \
            || die "Bad --version '$PIN' (use 1.2.3, v1.2.3, 1.2.3-rc1)" "$EX_USAGE"
        VERSION="${PIN#v}"
    fi
    if fancy; then command clear >/dev/null 2>&1 || true; fi
    # The tagline advertises a fresh install, so it must not appear on
    # update/uninstall/repair where it reads as if work were about to start.
    local subtitle
    case "$ACTION" in
        install) subtitle="Secure VPN node — up and running in a few minutes" ;;
        *)      subtitle="Secure VPN node" ;;
    esac
    line ""
    line "  ${B}OVNode installer${NC}  ${GY}v${VERSION}${NC}"
    line "  ${GY}${subtitle}${NC}"
    line ""

    case "$ACTION" in
        uninstall) do_uninstall; exit "$EX_OK" ;;
        update)    confirm "Update OVNode now?" || exit "$EX_OK"; do_update; exit "$EX_OK" ;;
        recover-update) do_recover_update; exit "$EX_OK" ;;
        repair-unit) do_repair_unit; exit "$EX_OK" ;;
        interactive) INTERACTIVE=1 ;;
    esac

    # Validation must precede the already-installed guard, otherwise a caller
    # invoking `install --port abc` gets exit 3 (Already installed) instead
    # of exit 2 with the usage message. When flags or OVN_* inputs are
    # present the values are checkable right away, even on an installed host.
    if [[ "$CLI_FLAGS" -eq 1 || "$ENV_INPUTS" -eq 1 ]]; then
        [[ -n "$PORT" ]]      || PORT="$DEFAULT_PORT"
        [[ -n "$TLS_METHOD" ]]|| TLS_METHOD="selfsigned"
        [[ -n "$VPN_PORTS" ]] || VPN_PORTS="$DEFAULT_VPN"
        [[ -n "$NODE_NAME" ]] || NODE_NAME="ovnode"
        validate_input
    fi

    # install
    if [[ -d "$APP_DIR" ]]; then
        if [[ "$YES" -eq 1 ]]; then
            die "Already installed ($APP_DIR exists). Run 'update' to refresh or 'uninstall' first." "$EX_ALREADY"
        fi
        installed_menu
        exit "$EX_OK"
    fi

    # Bare interactive invocation → friendly start menu (fresh installs only). Scripts/flags and
    # OVN_* env configuration keep the original machine path untouched.
    if [[ "$CMD_GIVEN" -eq 0 && "$CLI_FLAGS" -eq 0 && "$ENV_INPUTS" -eq 0 && "$YES" -eq 0 ]] && is_tty; then
        start_menu
    fi

    detect_os
    if [[ "${INTERACTIVE:-0}" -eq 1 ]] || { [[ "$YES" -eq 0 ]] && is_tty && [[ -z "$PORT" || -z "$API_KEY" ]]; }; then
        interactive_setup
    else
        : "${PORT:=$(find_free_port "$DEFAULT_PORT")}"
        : "${VPN_PORTS:=$DEFAULT_VPN}"
        : "${NODE_NAME:=ovnode}"
        : "${TLS_METHOD:=selfsigned}"
        : "${VPN_PROTO:=udp}"
        [[ -n "$API_KEY" ]] || generate_api_key
    fi
    validate_input

    field "OS"        "$OS_NAME"
    field "Version"   "v$VERSION (verified release)"
    field "Mode"      "$([ "$DOCKER" -eq 1 ] && echo Docker || echo Host)"
    field "Node"      "$NODE_NAME"
    field "Service"   "$PORT"
    field "OpenVPN"   "$(vpn_ports_label)/$VPN_PROTO"
    field "TLS"       "$TLS_METHOD"
    field "Install"   "$APP_DIR"
    field "Data"      "$DATA_BASE/$NODE_NAME"
    sep
    # No extra confirm: the review card above is the confirmation, same as
    # the panel installer.

    do_install
}

main "$@"
