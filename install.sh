wait_health() {
    local url="$1" tries="${2:-30}" i
    for i in $(seq 1 "$tries"); do
        curl -fsSk -o /dev/null --max-time 3 "$url" 2>/dev/null && return 0
        sleep 1
    done
    return 1
}

# ── Source / environment ───────────────────────────────────────────────
release_base() { printf 'ovnode-%s' "$VERSION"; }

release_url() {
    printf 'https://github.com/%s/releases/download/v%s/%s.tar.gz' \
        "$REPO" "$VERSION" "$(release_base)"
}

release_checksum_url() {
    printf 'https://github.com/%s/releases/download/v%s/%s.sha256' \
        "$REPO" "$VERSION" "$(release_base)"
}

# Download the versioned release file into $1 (an existing directory).
# The .sha256 sidecar is verified when published; a missing sidecar only
# warns (older releases).
fetch_release() {
    local dest="$1" work base
    base="$(release_base)"
    work="$(mktemp -d /tmp/ovn.XXXXXX)"
    run "Downloading release v${VERSION}" \
        curl -fsSLo "$work/$base.tar.gz" "$(release_url)" \
        || { rm -rf "$work"; die "No release file for v${VERSION} — try --from-source" "$EX_ERROR"; }
    if curl -fsSLo "$work/$base.sha256" "$(release_checksum_url)" 2>/dev/null; then
        ( cd "$work" && sha256sum -c "$base.sha256" >/dev/null ) \
            || { rm -rf "$work"; die "Release checksum mismatch for v${VERSION}" "$EX_ERROR"; }
        step "Checksum ok"
    else
        warn "No checksum file — skipping verification"
    fi
    mkdir -p "$dest"
    tar -xzf "$work/$base.tar.gz" -C "$dest" >/dev/null 2>&1 || { rm -rf "$work"; die "Extract failed" "$EX_ERROR"; }
    rm -rf "$work"
    step "Release extracted"
}

fetch_source() {
    if [[ "$SRC" == "release" ]]; then
        fetch_release "$APP_DIR"
        return
    fi
    if command -v git >/dev/null 2>&1; then
        run "Cloning repository ($BRANCH)" \
            git clone --depth 1 --branch "$BRANCH" "https://github.com/${REPO}.git" "$APP_DIR"
    else
        local tmp
        tmp="$(mktemp /tmp/ovn.XXXXXX.tar.gz)"
        run "Downloading source tarball" \
            curl -fsSLo "$tmp" "https://github.com/${REPO}/archive/refs/heads/${BRANCH}.tar.gz"
        mkdir -p "$APP_DIR"
        tar -xzf "$tmp" --strip-components=1 -C "$APP_DIR" >/dev/null 2>&1 || die "Extract failed"
        rm -f "$tmp"
    fi
}

write_env() {
    # Note: TUNNEL_ADDRESS is intentionally NOT written here — the node's
    # pydantic Settings rejects extra env fields, and the panel pushes the
    # tunnel address via /sync/config when the node is added/updated.
    cat > "$APP_DIR/.env" << EOF
NODE_NAME=${NODE_NAME}
DATA_DIR=${DATA_BASE}/${NODE_NAME}
SERVICE_PORT=${PORT}
API_KEY=${API_KEY}
OPENVPN_PORT=${VPN_PORT}
OVNODE_PROTO=${VPN_PROTO:-tcp}
TLS_METHOD=${TLS_METHOD}
$( if [[ -n "$EXTRA_PORTS" ]]; then echo "OVNODE_EXTRA_PORTS=${EXTRA_PORTS}"; fi )
$( if [[ "$IPV6" -eq 1 ]]; then echo "OVNODE_ENABLE_IPV6=1"; fi )
$( if [[ -n "$TLS_KEY" ]]; then echo "SSL_KEYFILE=${TLS_KEY}"; fi )
$( if [[ -n "$TLS_CERT" ]]; then echo "SSL_CERTFILE=${TLS_CERT}"; fi )
EOF
    chmod 600 "$APP_DIR/.env"
