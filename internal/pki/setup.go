package pki

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func SetupEasyRSA() error {
	easyrsaDir := EasyRSADir()
	easyrsaBin := filepath.Join(easyrsaDir, "easyrsa")
	varsPath := filepath.Join(easyrsaDir, "vars")

	// If easy-rsa is already in place, just update the vars file
	if _, err := os.Stat(easyrsaBin); err == nil {
		return writeEasyRSAVars(varsPath)
	}

	// Copy easy-rsa from system location
	src := "/usr/share/easy-rsa"
	if _, err := os.Stat(src); err != nil {
		// Try to find easy-rsa via dpkg
		output, err := exec.Command("dpkg", "-L", "easy-rsa").Output()
		if err == nil {
			for _, line := range strings.Split(string(output), "\n") {
				if strings.HasPrefix(line, "/usr/share/easy-rsa/") {
					src = "/usr/share/easy-rsa"
					break
				}
			}
		}
	}

	if _, err := os.Stat(src); err != nil {
		return fmt.Errorf("easy-rsa not found at %s", src)
	}

	// Copy easy-rsa to destination
	if err := copyDir(src, easyrsaDir); err != nil {
		return fmt.Errorf("failed to copy easy-rsa: %w", err)
	}

	// Make easyrsa executable
	binPath := filepath.Join(easyrsaDir, "easyrsa")
	if err := os.Chmod(binPath, 0o755); err != nil {
		return fmt.Errorf("failed to make easyrsa executable: %w", err)
	}

	return writeEasyRSAVars(filepath.Join(easyrsaDir, "vars"))
}

func writeEasyRSAVars(varsPath string) error {
	// If vars file already exists, don't overwrite (preserve existing config)
	if _, err := os.Stat(varsPath); err == nil {
		return nil
	}

	content := "# Generated by OVNode - ECDSA defaults (safe to edit)\n" +
		"set_var EASYRSA_ALGO \"ec\"\n" +
		"set_var EASYRSA_CURVE \"prime256v1\"\n" +
		"set_var EASYRSA_BATCH \"1\"\n" +
		"set_var EASYRSA_NO_PASS \"1\"\n" +
		"set_var EASYRSA_CA_EXPIRE \"3650\"\n" +
		"set_var EASYRSA_CERT_EXPIRE \"1825\"\n" +
		"set_var EASYRSA_CRL_DAYS \"365\"\n" +
		"# EASYRSA_REQ_CN is intentionally unset: easy-rsa only allows it\n" +
		"# for build-ca. Each server/client cert sets its CN positionally.\n"

	if err := os.WriteFile(varsPath, []byte(content), 0o644); err != nil {
		return fmt.Errorf("failed to write vars file: %w", err)
	}
	return nil
}

func copyDir(src, dst string) error {
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		relPath, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		dstPath := filepath.Join(dst, relPath)
		if info.IsDir() {
			return os.MkdirAll(dstPath, info.Mode())
		}
		return copyFile(path, dstPath)
	})
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}
